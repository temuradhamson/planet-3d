export function translit(name) {
  if (!name) return name;
  if (/[А-Яа-яЁёҚқҒғҲҳӮӯ]/.test(name)) return name;
  let s = name;
  s = s.replace(/skiy\b/gi, "ский").replace(/sky\b/gi, "ский");
  let out = "";
  for (let i = 0; i < s.length; ) {
    const rest = s.slice(i);
    const dig = DIGRAPHS.find(([a]) => rest.toLowerCase().startsWith(a));
    if (dig) {
      const chunk = rest.slice(0, dig[0].length);
      out += chunk[0] === chunk[0].toUpperCase() ? cap(dig[1]) : dig[1];
      i += dig[0].length;
      continue;
    }
    const ch = s[i];
    const low = ch.toLowerCase();
    if (LETTERS[low]) {
      out += ch === ch.toUpperCase() ? cap(LETTERS[low]) : LETTERS[low];
    } else out += ch;
    i += 1;
  }
  return out.replace(/ ramion$/i, " район").replace(/\s+/g, " ").trim();
}

function cap(s) {
  return s.charAt(0).toUpperCase() + s.slice(1);
}

export function ruName(rec) {
  if (rec?.ru) return rec.ru;
  if (rec?.nameRu) return rec.nameRu;
  return rec?.name || rec?.title || "—";
}

export function displayAdminName(iso, name) {
  const rec = ADM1[`${iso}|${name}`] || ADM2_FACTS[`${iso}|${name}`];
  if (rec?.ru) return rec.ru;
  let s = name;
  for (const [re, to] of SUFFIX) s = s.replace(re, to);
  return translit(s);
}

export function countryFact(iso) {
  return COUNTRY_FACTS[iso] || {};
}

export function admFact(iso, name, level) {
  const key = `${iso}|${name}`;
  return (level === "adm1" ? ADM1[key] : ADM2_FACTS[key]) || {};
}

